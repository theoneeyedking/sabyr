def static_reply(scheme: str, lang: str, turn: int) -> str:
    """turn — номер реплики ассистента, начиная с 1."""
    if turn == 1:
        return (OPENING.get(scheme) or OPENING["unknown"])[lang]
    if turn == 2:
        return scheme_info(scheme, lang)["how"]
    if turn == 3:
        return ADVICE[lang]
    return CLOSING[lang]
