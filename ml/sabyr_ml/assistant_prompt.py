def format_amount(amount) -> str:
    return f"{int(float(amount)):,}".replace(",", " ")


def build_system_prompt(lang: str, scheme: str, amount, reasons: list[str], level: str) -> str:
    lang = lang if lang in ("ru", "kz") else "ru"
    brief = SCHEME_BRIEF.get(scheme, SCHEME_BRIEF["unknown"])[lang]
    return _RULES[lang].format(max_turns=MAX_TURNS) + _CONTEXT[lang].format(
        brief=brief, amount=format_amount(amount), reasons="; ".join(reasons) or "—",
        level=_LEVEL[lang].get(level, level), extra=_PAUSE[lang] if level == "high" else "")


def build_messages(lang: str, history: list[dict]) -> list[dict]:
    """history: [{role: assistant|user, text}] -> сообщения для LLM (всегда начинаются с реплики user)."""
    lang = lang if lang in ("ru", "kz") else "ru"
    return [{"role": "user", "content": START_MARKER[lang]}] + [
        {"role": m["role"], "content": m["text"]} for m in history]
